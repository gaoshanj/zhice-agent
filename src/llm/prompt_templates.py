# ── 构建 messages ─────────────────────────────────────────────

def build_section_messages(section_num: int, **kwargs) -> list[dict]:
    """根据章节号，构建传给 LLM 的 messages 列表。

    Args:
        section_num: 1-6，对应 6 个章节
        **kwargs: 传递给模板的变量（company, visit_target 等）

    Returns:
        list[dict]: [{"role": "system", ...}, {"role": "user", ...}]
    """
    template_map = {
        1: SECTION1_SNAPSHOT,
        2: SECTION2_OPPORTUNITY,
        3: SECTION3_CROSS_SELL,
        4: SECTION4_STRATEGY,
        5: SECTION5_TALK_SCRIPT,
        6: SECTION6_ACTION_PLAN,
    }
    template = template_map.get(section_num, SECTION1_SNAPSHOT)
    user_content = template.format(**kwargs)

    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user_content},
    ]


